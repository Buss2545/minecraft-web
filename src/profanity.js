// ตัวกรองคำหยาบ (ไทย + อังกฤษ) ฝั่งเซิร์ฟเวอร์: maskBad() แทนคำหยาบด้วย * • hasBad() ตรวจว่ามีหรือไม่
// ภาษาไทยไม่มีช่องว่างระหว่างคำ จึงใช้การจับข้อความย่อย พร้อมข้อยกเว้นของคำปกติที่มีคำหยาบซ่อนอยู่ (เช่น หีบ แม่งาน กะหรี่ปั๊บ)
// ภาษาอังกฤษรองรับการแอบสะกด (f u c k แบบมีตัวเลข/สัญลักษณ์แทนตัวอักษร เช่น sh1t, f*ck ไม่ครอบคลุม) และตัวอักษรซ้ำ (fuuuck)
// ข้อจำกัด: ไม่ใช่ระบบสมบูรณ์ คนที่ตั้งใจเลี่ยงยังเลี่ยงได้ แอดมินจึงมีรายงานและปิดเสียงเสริม

const TH = [
  "เหี้ย", "เหี้", "สัส", "ส้นตีน", "ควย", "เย็ด", "เงี่ยน", "ตอแหล", "ระยำ", "ชิบหาย", "จัญไร", "อีดอก", "ไอ้สัตว์", "อีสัตว์", "ชาติหมา", "อีหมา", "ไอ้หมา", "สันดานหมา", "ไอ้ควาย", "อีควาย", "พ่อมึงตาย", "แม่มึงตาย", "ไอ้เหี้ย", "ไอ้สัส", "อีเหี้ย", "แตด", "หำ", "จู๋", "ปากหมา",
  "แม่ง(?!าน)", "สัด(?!ส่วน)", "ห่า(?![งนว])", "หี(?![บนย])", "เชี่ย(?!ว)", "กะหรี่(?!ปั๊บ|ปั๊ป)", "ไอ้บ้า(?!น)", "ฟาย(?![ลบ])",
];
const EN = [
  ["fuck", 0], ["fucker", 0], ["motherfucker", 0], ["shit", 0], ["bullshit", 0], ["bitch", 0], ["asshole", 0], ["cunt", 1], ["nigger", 0], ["nigga", 0], ["faggot", 0], ["whore", 0], ["slut", 0], ["bastard", 0], ["pussy", 0], ["retard", 1],
  ["dick", 1], ["cock", 1], ["ass", 1], ["tits", 1], ["porn", 1], ["rape", 1], ["wtf", 1], ["stfu", 1],
];
const SUB = { a: "[a@4]", i: "[i1!|]", o: "[o0]", e: "[e3]", s: "[s$5]", t: "[t7]", l: "[l1]", u: "[uv]" };
const enRe = (w, bound) => {
  const body = [...w].map((c) => (SUB[c] || c) + "+").join("[\\s._\\-*]?");
  return bound ? `(?<![a-z0-9])${body}(?:s|es|ed|ing|er)?(?![a-z0-9])` : body;
};
const RE = new RegExp(`(?:${TH.join("|")})|(?:${EN.map(([w, b]) => enRe(w, b)).join("|")})`, "giu");

export function hasBad(text) {
  RE.lastIndex = 0;
  return RE.test(String(text || ""));
}
export function maskBad(text) {
  return String(text || "").replace(RE, (m) => "*".repeat(Math.max(3, Math.min(m.length, 8))));
}
